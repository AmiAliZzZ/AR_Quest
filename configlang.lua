local function isPersianOrArabicLetter(cp)
    -- Arabic-script letters occupy U+0600..U+06FF. We use this only for
    -- word-boundary detection, so dictionary entries never replace a substring
    -- inside another word (e.g. "یک" inside "گاوصندوق").
    return cp and cp >= 0x0600 and cp <= 0x06FF
end

local function utf8CodepointAt(text, pos)
    local b = text:byte(pos)
    if not b then return nil, pos end
    if b < 0x80 then return b, pos + 1 end
    if b < 0xE0 then
        return (b - 0xC0) * 0x40 + (text:byte(pos + 1) - 0x80), pos + 2
    elseif b < 0xF0 then
        return (b - 0xE0) * 0x1000 + (text:byte(pos + 1) - 0x80) * 0x40 + (text:byte(pos + 2) - 0x80), pos + 3
    elseif b < 0xF8 then
        return (b - 0xF0) * 0x40000 + (text:byte(pos + 1) - 0x80) * 0x1000 + (text:byte(pos + 2) - 0x80) * 0x40 + (text:byte(pos + 3) - 0x80), pos + 4
    end
    return nil, pos + 1
end

local function previousCodepoint(text, pos)
    if pos <= 1 then return nil end
    local i = pos - 1
    while i > 1 and text:byte(i) >= 0x80 and text:byte(i) <= 0xBF do i = i - 1 end
    return utf8CodepointAt(text, i)
end

local function nextCodepoint(text, pos)
    return utf8CodepointAt(text, pos)
end

local function replaceOneKey(text, key, value)
    if key == '' then return text end
    local out = {}
    local cursor = 1
    local from = 1
    while true do
        local a, b = text:find(key, from, true)
        if not a then break end
        local before = previousCodepoint(text, a)
        local _, afterPos = utf8CodepointAt(text, b + 1)
        local after = utf8CodepointAt(text, b + 1)
        local keyFirst = utf8CodepointAt(key, 1)
        local keyLastPos = 1
        local keyLast
        while true do
            local cp, np = utf8CodepointAt(key, keyLastPos)
            if not cp then break end
            keyLast = cp
            if np > #key then break end
            keyLastPos = np
        end
        local leftBlocked = isPersianOrArabicLetter(keyFirst) and isPersianOrArabicLetter(before)
        local rightBlocked = isPersianOrArabicLetter(keyLast) and isPersianOrArabicLetter(after)
        if not leftBlocked and not rightBlocked then
            out[#out+1] = text:sub(cursor, a - 1)
            out[#out+1] = value
            cursor = b + 1
        else
            out[#out+1] = text:sub(cursor, b)
            cursor = b + 1
        end
        from = b + 1
    end
    if #out == 0 then return text end
    out[#out+1] = text:sub(cursor)
    return table.concat(out)
end

local function replaceWords(text, dict)
    local out = tostring(text or "")
    local keys = {}
    for k in pairs(dict) do keys[#keys+1] = k end
    table.sort(keys, function(a,b) return #a > #b end)
    for _, k in ipairs(keys) do
        out = replaceOneKey(out, k, dict[k])
    end
    return out
end

function ConfigLang.TranslateText(text, lang)
    if text == nil or type(text) ~= 'string' then return text end
    lang = tostring(lang or ConfigLang.Language or 'fa'):lower()
    if lang == 'fa' then return text end
    local dict = lang == 'ar' and AR or EN
    if lang == 'ar' then
        local outExtra = replaceWords(text, AR_EXTRA)
        outExtra = replaceWords(outExtra, AR_TOKEN_FALLBACK)
        return replaceWords(outExtra, dict)
    end
    if lang == 'en' then
        -- Exact/long phrase pass first, then the general dictionary. This prevents
        -- outputs such as "Request Chicken آماده" when a full quest label exists.
        local outExtra = replaceWords(text, EN_EXTRA)
        outExtra = replaceWords(outExtra, EN_TOKEN_FALLBACK)
        return replaceWords(outExtra, dict)
    end
    local out = replaceWords(text, dict)
    -- Do not strip Arabic output: Arabic/Persian share the same UTF-8 byte ranges.
    -- The previous fallback treated translated Arabic text as untranslated Persian and
    -- replaced the entire quest title with "مهمة". Keep the translated string intact.
    return out
end

local function ARQuestGetLocale()
    local lang = tostring(ConfigLang.Language or "fa"):lower()
    if not ConfigLang.Locales[lang] then lang = "fa" end
    return lang, ConfigLang.Locales[lang]
end
ConfigLang.GetLocale = ARQuestGetLocale
